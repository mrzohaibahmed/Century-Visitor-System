/* ===================================================================================== accounts */
CREATE TABLE dbo.users (
    id                   UNIQUEIDENTIFIER NOT NULL CONSTRAINT pk_users PRIMARY KEY,
    username             NVARCHAR(32)     NOT NULL,     -- unique ignoring case (column collation is CI)
    display_name         NVARCHAR(80)     NULL,
    password_hash        NVARCHAR(255)    NOT NULL,     -- argon2id string
    role                 VARCHAR(10)      NOT NULL CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'GUARD')),
    is_active            BIT              NOT NULL,
    must_change_password BIT              NOT NULL CONSTRAINT df_users_must_change DEFAULT 0,
    failed_login_count   INT              NOT NULL CONSTRAINT df_users_failed DEFAULT 0
                                          CONSTRAINT ck_users_failed CHECK (failed_login_count >= 0),
    locked_until         DATETIME2(3)     NULL,
    last_login_at        DATETIME2(3)     NULL,
    password_changed_at  DATETIME2(3)     NULL,
    created_at           DATETIME2(3)     NOT NULL,
    updated_at           DATETIME2(3)     NOT NULL,
    created_by           UNIQUEIDENTIFIER NULL CONSTRAINT fk_users_created_by REFERENCES dbo.users (id),
    CONSTRAINT ck_users_username CHECK (LEN(username) >= 3)
);
CREATE UNIQUE INDEX ux_users_username ON dbo.users (username);              -- login lookup, any case
CREATE INDEX ix_users_active_admins ON dbo.users (role, is_active);         -- "last active admin" rule

CREATE TABLE dbo.sessions (
    id              UNIQUEIDENTIFIER NOT NULL CONSTRAINT pk_sessions PRIMARY KEY,
    token_hash      CHAR(64) COLLATE Latin1_General_100_BIN2 NOT NULL,   -- SHA-256 hex; the token is only in the cookie
    csrf_token_hash CHAR(64) COLLATE Latin1_General_100_BIN2 NOT NULL,
    user_id         UNIQUEIDENTIFIER NOT NULL CONSTRAINT fk_sessions_user REFERENCES dbo.users (id),
    gate_id         UNIQUEIDENTIFIER NULL,                               -- FK added after dbo.gates
    created_at      DATETIME2(3)     NOT NULL,
    last_seen_at    DATETIME2(3)     NOT NULL,
    expires_at      DATETIME2(3)     NOT NULL,
    revoked_at      DATETIME2(3)     NULL,
    revoked_reason  VARCHAR(32)      NULL,
    ip              VARCHAR(45)      NULL,                               -- IPv6 fits
    user_agent      NVARCHAR(256)    NULL,
    CONSTRAINT ck_sessions_token_hex CHECK (token_hash NOT LIKE '%[^0-9a-f]%' AND LEN(token_hash) = 64)
);
CREATE UNIQUE INDEX ux_sessions_token_hash ON dbo.sessions (token_hash);   -- every request
CREATE INDEX ix_sessions_user ON dbo.sessions (user_id) WHERE revoked_at IS NULL;   -- revoke all on disable/reset
CREATE INDEX ix_sessions_expires ON dbo.sessions (expires_at);              -- background clean-up (was TTL)

CREATE TABLE dbo.rate_limits (                                              -- fixed-window login counters
    window_key VARCHAR(200) COLLATE Latin1_General_100_BIN2 NOT NULL CONSTRAINT pk_rate_limits PRIMARY KEY,
    count      INT          NOT NULL,                                       -- "login-ip:<ip>:<window>"
    expires_at DATETIME2(3) NOT NULL
);
CREATE INDEX ix_rate_limits_expires ON dbo.rate_limits (expires_at);        -- background clean-up (was TTL)
GO

