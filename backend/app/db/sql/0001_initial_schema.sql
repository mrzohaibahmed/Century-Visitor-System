    id                UNIQUEIDENTIFIER NOT NULL CONSTRAINT pk_entry_denials PRIMARY KEY,
    at                DATETIME2(3)     NOT NULL,  -- = the WATCHLIST_MATCH audit entry's timestamp
    reason            VARCHAR(20)      NOT NULL CONSTRAINT ck_entry_denials_reason CHECK (reason IN ('WATCHLIST')),
    source            VARCHAR(20)      NOT NULL CONSTRAINT ck_entry_denials_source CHECK (source IN
                          ('check_in', 'lookup', 'audit_backfill')),
    source_audit_id   UNIQUEIDENTIFIER NOT NULL,  -- the WATCHLIST_MATCH audit entry (dedup key)
