/* =====================================================================================================
   Century Gate VMS - SQL Server schema, version 1 (the first Alembic migration, 0001).
   Target: SQL Server 2019+ (Express is enough), database century_gate_vms on .\SQLEXPRESS.

   Design rules
   - One table per kind of record; lists inside a record (belongings, replaced passes...) are child
     tables (no Oracle alignment yet).
   - IDs: UNIQUEIDENTIFIER generated by the application. To keep inserts
     append-only, the app generates "sequential" GUIDs whose LAST 6 bytes hold the time (SQL Server
     sorts GUIDs by those bytes first), so clustered primary keys do not fragment.
   - Times: DATETIME2(3) holding UTC, in whole milliseconds (the app rounds the same way, so keyset
     cursors stay exact).
     Repositories attach tzinfo=UTC when reading.
   - Text: NVARCHAR everywhere (names can be Urdu). Database collation Latin1_General_100_CI_AS_SC:
     case-INsensitive, accent-sensitive, so the
     case-insensitive unique usernames / gate / department names are plain unique indexes.
     Hashes and machine keys use a binary collation (exact, fast).
   - Enumerations: CHECK constraints with the same values as the API schemas (app/schemas).
   - FILTERED unique indexes hold the business rules: one active visit per visitor, one active
     watchlist entry per identity, ...
   - Foreign keys on references between business records. Records are deactivated,
     never deleted, so they never block. NOT on audit_logs / entry_denials: those must never fail to
     insert and may point at anything.
   - No TTL indexes in SQL Server: expired sessions and rate-limit windows are deleted by a small
     background clean-up in the API (Express has no SQL Agent jobs).
   - Transactions: READ_COMMITTED_SNAPSHOT ON (readers never block writers); the app retries a
     transaction chosen as a deadlock victim (1205).
   - Column lengths come from the API schemas (the modules in app/schemas); the CHECKs repeat their
     validation rules.
   ===================================================================================================== */

