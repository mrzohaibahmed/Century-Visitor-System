/* ===================================================================================== watchlist */
CREATE TABLE dbo.watchlist (
    id               UNIQUEIDENTIFIER NOT NULL CONSTRAINT pk_watchlist PRIMARY KEY,
    identifier       NVARCHAR(72)     NOT NULL,     -- "<TYPE>:<normalised number>"
    -- "OTHER" numbers compared with spaces, / and - ignored (was a $regex): computed, indexed.
    identifier_compact AS CAST(REPLACE(REPLACE(REPLACE(identifier, N' ', N''), N'/', N''), N'-', N'') AS NVARCHAR(72))
                       PERSISTED,
    identity_type    VARCHAR(10)      NOT NULL CONSTRAINT ck_watchlist_identity_type
                                           CHECK (identity_type IN ('CNIC', 'PASSPORT', 'OTHER')),
    identity_number  NVARCHAR(60)     NOT NULL,
    name             NVARCHAR(60)     NULL,
    name_search      NVARCHAR(60)     NULL,
    reason           NVARCHAR(500)    NOT NULL,
    is_active        BIT              NOT NULL,     -- 0 = disabled (lifted); entries are never deleted
    expires_at       DATETIME2(3)     NULL,
    created_by       UNIQUEIDENTIFIER NOT NULL CONSTRAINT fk_watchlist_created_by REFERENCES dbo.users (id),
    created_by_name  NVARCHAR(80)     NULL,
    created_at       DATETIME2(3)     NOT NULL,
    updated_by       UNIQUEIDENTIFIER NULL CONSTRAINT fk_watchlist_updated_by REFERENCES dbo.users (id),
    updated_at       DATETIME2(3)     NULL,
    disabled_by      UNIQUEIDENTIFIER NULL CONSTRAINT fk_watchlist_disabled_by REFERENCES dbo.users (id),
    disabled_by_name NVARCHAR(80)     NULL,
    disabled_at      DATETIME2(3)     NULL,
    disabled_reason  NVARCHAR(200)    NULL
);
-- Screening; one ACTIVE ban per identity (inactive history kept) -- was a partial unique index.
CREATE UNIQUE INDEX ux_watchlist_active_identifier ON dbo.watchlist (identifier) WHERE is_active = 1;
CREATE INDEX ix_watchlist_compact ON dbo.watchlist (identifier_compact) WHERE is_active = 1;
CREATE INDEX ix_watchlist_newest_first ON dbo.watchlist (created_at DESC, id DESC);   -- management screen
CREATE INDEX ix_watchlist_identifier_history ON dbo.watchlist (identifier, created_at DESC);
CREATE INDEX ix_watchlist_name_prefix ON dbo.watchlist (name_search) WHERE name_search IS NOT NULL;
GO

