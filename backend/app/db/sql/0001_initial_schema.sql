CREATE TABLE dbo.visits (
    id                   UNIQUEIDENTIFIER NOT NULL CONSTRAINT pk_visits PRIMARY KEY,
    -- V-26-OCT-02-001 (and the earlier V-26-0210-001 / V-2026-000123 formats)
    visit_number         VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    visitor_id           UNIQUEIDENTIFIER NOT NULL CONSTRAINT fk_visits_visitor REFERENCES dbo.visitors (id),
    host_id              UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_host REFERENCES dbo.hosts (id),
    host_unlisted        BIT              NOT NULL,
    department_id        UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_department REFERENCES dbo.departments (id),
    gate_id              UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_gate REFERENCES dbo.gates (id),
    checkout_gate_id     UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_checkout_gate REFERENCES dbo.gates (id),
    reason_code          VARCHAR(20)      NOT NULL CONSTRAINT ck_visits_reason CHECK (reason_code IN
                             ('OFFICIAL_MEETING', 'INTERVIEW', 'DELIVERY', 'MAINTENANCE', 'CONTRACTOR_WORK',
                              'PERSONAL', 'OTHER')),
    reason_note          NVARCHAR(200)    NULL,
    vehicle_registration VARCHAR(15)      NULL,      -- upper-case letters, digits, hyphens
    status               VARCHAR(12)      NOT NULL CONSTRAINT ck_visits_status CHECK (status IN
                             ('SCHEDULED', 'EXPECTED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED', 'EXPIRED', 'NO_SHOW')),
    check_in_at          DATETIME2(3)     NOT NULL,
    check_out_at         DATETIME2(3)     NULL,
    checked_in_by        UNIQUEIDENTIFIER NOT NULL CONSTRAINT fk_visits_checked_in_by REFERENCES dbo.users (id),
    checked_out_by       UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_checked_out_by REFERENCES dbo.users (id),
    checkout_method      VARCHAR(12)      NULL CONSTRAINT ck_visits_checkout_method CHECK (checkout_method IN
                             ('MANUAL', 'VISIT_NUMBER', 'ID_NUMBER', 'QR', 'AUTO')),
    photo_id             UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_photo REFERENCES dbo.photos (id),
    -- snapshot: names as they were at the time (was the embedded "snapshot" object)
    snap_visitor_name         NVARCHAR(60) NOT NULL,
    snap_host_name            NVARCHAR(60) NULL,
    snap_department_name      NVARCHAR(60) NULL,
    snap_gate_name            NVARCHAR(60) NULL,
    snap_checked_in_by_name   NVARCHAR(80) NULL,
    snap_checked_out_by_name  NVARCHAR(80) NULL,
    snap_checkout_gate_name   NVARCHAR(60) NULL,
    -- the QR pass (was the embedded "pass" object; NULL columns = no pass issued)
    pass_token_hash      CHAR(64) COLLATE Latin1_General_100_BIN2 NULL,
    pass_issued_at       DATETIME2(3)     NULL,
    pass_expires_at      DATETIME2(3)     NULL,
    pass_issued_by       UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_pass_issued_by REFERENCES dbo.users (id),
    pass_revoked_at      DATETIME2(3)     NULL,
    pass_revoked_by      UNIQUEIDENTIFIER NULL CONSTRAINT fk_visits_pass_revoked_by REFERENCES dbo.users (id),
    -- encrypted copy of the QR text for matching belongings prints (core/secrets.encrypt), when a key is set
    pass_qr_version      TINYINT          NULL,
    pass_qr_kid          VARCHAR(32)      NULL,
    pass_qr_nonce        VARBINARY(12)    NULL,
    pass_qr_ct           VARBINARY(256)   NULL,
    -- Personal Material Returnable slip present (its fields: dbo.visit_personal_material)
    created_at           DATETIME2(3)     NOT NULL,
    updated_at           DATETIME2(3)     NOT NULL,
    CONSTRAINT ck_visits_pass_complete CHECK (pass_token_hash IS NULL
        OR (pass_issued_at IS NOT NULL AND pass_expires_at IS NOT NULL)),
    CONSTRAINT ck_visits_pass_hex CHECK (pass_token_hash IS NULL OR pass_token_hash NOT LIKE '%[^0-9a-f]%')
);
CREATE UNIQUE INDEX ux_visits_visit_number ON dbo.visits (visit_number);        -- manual check-out
